/* Quello shared game artwork loader. Square icons and wide banners are separate assets. */
(function () {
  'use strict';

  const ROBLOX_PLACES = ['6516141723', '18186775539', '138837502355157', '16732694052'];
  const STEAM = {
    'dishonored': '205100', 'metro': '286690', 'horizon-zero-dawn': '1151640',
    'horizon-forbidden-west': '2420110', 'tomb-raider': '203160',
    'undertale': '391540', 'portal': '400', 'demon-slayer': '1490890'
  };
  const STATIC_ICONS = {
    'murder-drones': ['https://glitchproductions.store/cdn/shop/files/Poster_Murder-Drones-Default-01.png?v=1701668116'],
    'growth-of-giggle-rp': ['https://unavatar.io/youtube/UC8tOyxdey3zEPIiEdGNp3Zg']
  };
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const safeJson = async url => {
    try {
      const response = await fetch(url, { method: 'GET', mode: 'cors', credentials: 'omit', cache: 'no-store' });
      if (!response.ok) return null;
      return await response.json();
    } catch (_) { return null; }
  };
  async function retryJson(url, attempts = 3) {
    for (let i = 0; i < attempts; i++) {
      const result = await safeJson(url);
      if (result) return result;
      if (i < attempts - 1) await wait(500 * (i + 1));
    }
    return null;
  }
  function firstImage(data, targetId) {
    const rows = data && Array.isArray(data.data) ? data.data : [];
    const row = rows.find(item => targetId == null || String(item.targetId ?? item.universeId) === String(targetId)) || rows[0];
    if (!row) return null;
    if (row.imageUrl) return row.imageUrl;
    if (Array.isArray(row.thumbnails) && row.thumbnails[0]) return row.thumbnails[0].imageUrl || null;
    return null;
  }

  let robloxIconsPromise;
  let robloxBannersPromise;
  function loadRobloxIcons() {
    if (robloxIconsPromise) return robloxIconsPromise;
    robloxIconsPromise = (async () => {
      const icons = new Map();
      const ids = ROBLOX_PLACES.join(',');
      // One request for all square place icons prevents a burst of parallel requests/rate limits.
      const data = await retryJson('https://thumbnails.roblox.com/v1/places/gameicons?placeIds=' + ids + '&returnPolicy=AutoGenerated&size=512x512&format=Png&isCircular=false');
      for (const row of (data && data.data) || []) {
        if (row.imageUrl && row.state !== 'Pending') icons.set(String(row.targetId), row.imageUrl);
      }
      return icons;
    })();
    return robloxIconsPromise;
  }
  function loadRobloxBanners() {
    if (robloxBannersPromise) return robloxBannersPromise;
    robloxBannersPromise = (async () => {
      const placeToBanner = new Map();
      const ids = ROBLOX_PLACES.join(',');
      // Resolve all place IDs to universe IDs in one request, then request all wide thumbnails together.
      const details = await retryJson('https://games.roblox.com/v1/games/multiget-place-details?placeIds=' + ids);
      const universeIds = new Map();
      if (Array.isArray(details)) {
        for (const row of details) {
          if (row && row.placeId && row.universeId) universeIds.set(String(row.placeId), String(row.universeId));
        }
      }
      const uniqueUniverses = [...new Set([...universeIds.values()])];
      const banners = new Map();
      if (uniqueUniverses.length) {
        const data = await retryJson('https://thumbnails.roblox.com/v1/games/multiget/thumbnails?universeIds=' + uniqueUniverses.join(',') + '&countPerUniverse=1&defaults=true&size=768x432&format=Png&isCircular=false');
        for (const row of (data && data.data) || []) {
          const image = row.imageUrl || (row.thumbnails && row.thumbnails[0] && row.thumbnails[0].imageUrl);
          if (image && row.universeId) banners.set(String(row.universeId), image);
        }
      }
      // Direct per-universe fallback is only used for missing banner results.
      for (const [place, universe] of universeIds) {
        if (banners.has(universe)) continue;
        const data = await retryJson('https://thumbnails.roblox.com/v1/games/' + encodeURIComponent(universe) + '/thumbnails?size=768x432&format=Png&isCircular=false&sortOrder=Asc&limit=10', 2);
        const image = firstImage(data);
        if (image) banners.set(universe, image);
      }
      for (const [place, universe] of universeIds) if (banners.has(universe)) placeToBanner.set(place, banners.get(universe));
      return placeToBanner;
    })();
    return robloxBannersPromise;
  }

  function gameKeyFromLink(link) {
    try { return new URL(link.href, location.href).searchParams.get('game') || ''; }
    catch (_) { return ''; }
  }
  function steamIconUrls(key) {
    const id = STEAM[key];
    if (!id) return [];
    return [
      'https://shared.akamai.steamstatic.com/store_item_assets/steam/apps/' + id + '/logo.png',
      'https://shared.akamai.steamstatic.com/store_item_assets/steam/apps/' + id + '/library_600x900.jpg'
    ];
  }
  function staticIconUrls(key, box) {
    if (steamIconUrls(key).length) return steamIconUrls(key);
    if (STATIC_ICONS[key]) return STATIC_ICONS[key];
    const declared = box && box.dataset.gameArt;
    return declared ? [declared] : [];
  }
  function setImage(img, box, urls) {
    if (!img || !Array.isArray(urls) || !urls.length) return;
    let index = 0;
    const fallback = box && box.querySelector('.about-favorite-fallback');
    const tryNext = () => {
      if (index >= urls.length) {
        if (box) box.classList.remove('has-image');
        if (fallback) fallback.hidden = false;
        return;
      }
      const url = urls[index++];
      img.onload = () => {
        if (box) box.classList.add('has-image');
        if (fallback) fallback.hidden = true;
      };
      img.onerror = tryNext;
      img.referrerPolicy = 'no-referrer';
      img.decoding = 'async';
      img.src = url;
    };
    tryNext();
  }
  function setBanner(link, url) {
    if (!link || !url) return;
    const probe = new Image();
    probe.referrerPolicy = 'no-referrer';
    probe.onload = () => {
      link.style.setProperty('--roblox-banner', 'url("' + url.replace(/"/g, '%22') + '")');
      link.classList.add('roblox-has-banner');
    };
    probe.src = url;
  }

  async function initAboutCards() {
    const cards = [...document.querySelectorAll('.about-favorite-icon')];
    const places = cards.filter(box => box.dataset.robloxPlace);
    // Load non-Roblox artwork immediately; Roblox API requests happen independently.
    for (const box of cards.filter(item => !item.dataset.robloxPlace)) {
      const link = box.closest('.about-favorite-link');
      setImage(box.querySelector('img'), box, staticIconUrls(gameKeyFromLink(link), box));
    }
    if (places.length) {
      const icons = await loadRobloxIcons();
      for (const box of places) {
        const place = box.dataset.robloxPlace;
        setImage(box.querySelector('img'), box, icons.has(place) ? [icons.get(place)] : []);
      }
    }
    if (places.length) {
      const banners = await loadRobloxBanners();
      for (const box of places) {
        const link = box.closest('.about-favorite-link');
        const place = box.dataset.robloxPlace;
        if (link && banners.has(place)) setBanner(link, banners.get(place));
      }
    }
  }

  async function loadUniverseIcon(game, box, img) {
    if (game && game.place) {
      const icons = await loadRobloxIcons();
      setImage(img, box, icons.has(String(game.place)) ? [icons.get(String(game.place))] : []);
      return;
    }
    const key = gameKeyFromLink(location.href);
    const urls = staticIconUrls(key, null);
    if (game && game.iconImg) urls.unshift(game.iconImg);
    setImage(img, box, urls.length ? urls : (game && game.img ? [game.img] : []));
  }

  async function loadUniverseBanner(game, img) {
    if (!img || !game) return;
    if (game.place) {
      const banners = await loadRobloxBanners();
      const url = banners.get(String(game.place));
      if (url) {
        img.referrerPolicy = 'no-referrer';
        img.src = url;
        img.style.display = 'block';
      } else img.style.display = 'none';
      return;
    }
    if (game.img) {
      img.referrerPolicy = 'no-referrer';
      img.onload = () => { img.style.display = 'block'; };
      img.onerror = () => { img.style.display = 'none'; };
      img.src = game.img;
    } else img.style.display = 'none';
  }

  window.QuelloGameArt = { loadUniverseIcon, loadUniverseBanner };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initAboutCards, { once: true });
  else initAboutCards();
})();
